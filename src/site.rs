/// Look up an embedded asset by its site-relative path (no leading slash).
pub fn get(path: &str) -> Option<&'static [u8]> {
    ASSETS.iter().find(|a| a.path == path).map(|a| a.bytes)
}

/// Is this build carrying the site? (Always true; kept as the honest predicate the
/// server asks before reporting "serving embedded pages".)
pub fn available() -> bool {
    !ASSETS.is_empty()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_whole_gui_is_embedded() {
        // the pages the GUI cannot start without
        for p in ["index.facet", "system.html", "tools.facet", "trade.html", "network.facet"] {
            assert!(get(p).is_some(), "missing embedded asset: {}", p);
        }
        assert!(available());
    }

    #[test]
    fn fonts_are_embedded_as_bytes() {
        let f = get("fonts/ligos-regular.woff2").expect("regular font");
        assert!(f.len() > 10_000, "font looks truncated");
        assert_eq!(&f[..4], b"wOF2", "WOFF2 magic survives embedding");
    }

    #[test]
    fn embedded_matches_the_repository_when_present() {
        // when the checkout is beside us (the dev case), every embedded byte must equal
        // the file on disk — otherwise the phone would serve a stale GUI
        for a in ASSETS {
            let p = std::path::Path::new("lib/site").join(a.path);
            if let Ok(disk) = std::fs::read(&p) {
                assert_eq!(disk, a.bytes, "embedded copy of {} is stale", a.path);
            }
        }
    }
}
