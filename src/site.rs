//! site — the GUI's pages, EMBEDDED in the binary.
//!
//! Orpheus's `.lat` libraries have always been `include_str!`-embedded, so the language
//! and every tool travel inside the executable. The web GUI was the one exception: it
//! read `lib/site/*` from disk. That is fine on a workstation and impossible on Android,
//! where an app's executable is extracted from the APK into `nativeLibraryDir` and there
//! is no repository checkout beside it.
//!
//! So the site travels too. `serve` prefers a real `--root` directory when one exists
//! (so editing a page and reloading still works during development); when the directory
//! is absent, these embedded copies answer instead — the single-binary path a phone
//! needs. Text pages are `include_str!`, the three webfonts `include_bytes!`.
//!
//! Generated by hand from `lib/site/` — the list is short and stable; a build script
//! would add a dependency-free-ness caveat for no real gain.

/// One embedded file: path relative to the site root, and its bytes.
pub struct Asset {
    pub path: &'static str,
    pub bytes: &'static [u8],
}

